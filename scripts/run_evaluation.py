"""Run every detector against every scenario/dataset from the command line.

The dashboard's "Detector Evaluation" panel and ``tests/test_evaluation.py``
are the only two places detection accuracy could previously be observed —
one requires a browser, the other only exercises small hand-built toy data.
This script runs the same pipeline the dashboard uses
(``load_network_data`` -> ``build_graph`` -> ``compute_node_metrics`` ->
``compare_algorithms``) against every scenario returned by
``src.scenarios.list_scenarios()`` — the four synthetic scenarios plus any
real dataset converted into ``data/`` (CTU-13, IoT-23, or anything else with a
matching ``.truth.json`` sidecar) — and prints precision/recall/F1 tables,
wall-clock timing, and the Lightweight GNN's resource profile.

Usage (run from the project root so ``data/*.truth.json`` resolves):

    .venv/bin/python scripts/run_evaluation.py                    # every scenario, threshold 0.65
    .venv/bin/python scripts/run_evaluation.py --list
    .venv/bin/python scripts/run_evaluation.py --scenario scanner botnet
    .venv/bin/python scripts/run_evaluation.py --threshold 0.5 0.65 0.8
    .venv/bin/python scripts/run_evaluation.py --no-gnn            # skip GNN training (faster)
    .venv/bin/python scripts/run_evaluation.py --output misc/chapter4_figures/evaluation_results.md

Or via ``make evaluate`` / ``make.bat evaluate`` (see the Makefile).
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import pandas as pd  # noqa: E402

from src.evaluation import compare_algorithms  # noqa: E402
from src.graph_builder import GraphBuildResult, build_graph  # noqa: E402
from src.loader import load_network_data  # noqa: E402
from src.metrics import compute_node_metrics  # noqa: E402
from src.scenarios import generate_scenario, list_scenarios  # noqa: E402

DEFAULT_THRESHOLD = 0.65


def _markdown_table(frame: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    """Render a DataFrame as a Markdown table without the ``tabulate`` dependency."""
    display = frame.copy()
    for column in display.columns:
        if pd.api.types.is_float_dtype(display[column]):
            display[column] = display[column].map(floatfmt.format)
    header = "| " + " | ".join(str(c) for c in display.columns) + " |"
    separator = "|" + "|".join("---" for _ in display.columns) + "|"
    rows = [
        "| " + " | ".join(str(v) for v in row) + " |"
        for row in display.itertuples(index=False)
    ]
    return "\n".join([header, separator, *rows])


def _prepare_scenario(key: str) -> tuple[pd.DataFrame, GraphBuildResult, tuple[str, ...], str]:
    scenario = generate_scenario(key)
    frame = load_network_data(scenario.frame)
    build_result = build_graph(frame)
    metrics = compute_node_metrics(build_result.graph, build_result.edge_frame)
    return metrics, build_result, scenario.true_anomalies, scenario.name


def evaluate_scenario(
    key: str, thresholds: list[float], include_gnn: bool
) -> dict:
    """Run the full pipeline once, score every threshold, and profile the GNN once."""
    metrics, build_result, truth, name = _prepare_scenario(key)
    graph = build_result.graph if include_gnn else None

    threshold_tables: dict[float, pd.DataFrame] = {}
    threshold_timings: dict[float, float] = {}
    for threshold in thresholds:
        start = time.perf_counter()
        table = compare_algorithms(metrics, truth, threshold=threshold, graph=graph)
        threshold_timings[threshold] = time.perf_counter() - start
        threshold_tables[threshold] = table

    profile = None
    if include_gnn:
        from src.gnn import gcn_autoencoder_with_profile

        _scored, profile = gcn_autoencoder_with_profile(metrics, build_result.graph)

    return {
        "key": key,
        "name": name,
        "nodes": build_result.graph.number_of_nodes(),
        "edges": build_result.graph.number_of_edges(),
        "true_anomalies": len(truth),
        "tables": threshold_tables,
        "timings": threshold_timings,
        "profile": profile,
    }


def _format_profile(profile) -> str:
    return (
        f"**Lightweight GNN resource profile:** {profile.parameter_count} parameters, "
        f"{profile.model_size_kb:.2f} KB, {profile.inference_ms_per_node:.4f} ms/node "
        f"over {profile.graph_nodes} nodes — target device: {profile.target_device} "
        f"({profile.target_ram_mb} MB RAM), fits budget: {profile.fits_target_ram}"
    )


def render_report(results: list[dict], thresholds: list[float]) -> str:
    lines: list[str] = ["# Detector Evaluation Results", ""]
    lines.append(
        f"Generated by `scripts/run_evaluation.py`. Thresholds: {', '.join(str(t) for t in thresholds)}."
    )
    lines.append("")

    for result in results:
        lines.append(f"## {result['name']} (`{result['key']}`)")
        lines.append("")
        lines.append(
            f"Graph: {result['nodes']} nodes, {result['edges']} edges, "
            f"{result['true_anomalies']} ground-truth anomalies."
        )
        lines.append("")
        for threshold, table in result["tables"].items():
            elapsed_ms = result["timings"][threshold] * 1000
            lines.append(f"**Threshold {threshold}** — detection completed in {elapsed_ms:.1f} ms")
            lines.append("")
            lines.append(_markdown_table(table))
            lines.append("")
        if result["profile"] is not None:
            lines.append(_format_profile(result["profile"]))
            lines.append("")

    # Summary pivot: F1 per algorithm per scenario, at the first threshold requested.
    primary_threshold = thresholds[0]
    summary_rows = []
    for result in results:
        table = result["tables"][primary_threshold].set_index("algorithm")["f1"]
        summary_rows.append(pd.Series(table, name=result["name"]))
    if summary_rows:
        summary = pd.DataFrame(summary_rows)
        summary.index.name = "Scenario"
        summary_reset = summary.reset_index()
        lines.append(f"## Summary: F1-score by algorithm and scenario (threshold {primary_threshold})")
        lines.append("")
        lines.append(_markdown_table(summary_reset))
        lines.append("")

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run every detector against every scenario/dataset and print evaluation tables.",
    )
    parser.add_argument(
        "--scenario",
        nargs="+",
        metavar="KEY",
        help="Scenario key(s) to run (default: every scenario returned by list_scenarios()).",
    )
    parser.add_argument(
        "--threshold",
        nargs="+",
        type=float,
        default=[DEFAULT_THRESHOLD],
        metavar="T",
        help=f"Detection threshold(s) to evaluate at (default: {DEFAULT_THRESHOLD}).",
    )
    parser.add_argument(
        "--no-gnn",
        action="store_true",
        help="Skip the Lightweight GNN (faster; also skips its resource profile).",
    )
    parser.add_argument(
        "--output",
        type=Path,
        metavar="PATH",
        help="Write the full Markdown report to this file, in addition to printing it.",
    )
    parser.add_argument(
        "--list",
        action="store_true",
        help="List available scenario keys and exit.",
    )
    args = parser.parse_args()

    available = list_scenarios()
    if args.list:
        for entry in available:
            print(f"{entry['key']:<20} {entry['name']}")
        return

    keys = args.scenario or [entry["key"] for entry in available]
    known_keys = {entry["key"] for entry in available}
    unknown = [key for key in keys if key not in known_keys]
    if unknown:
        parser.error(
            f"Unknown scenario key(s): {', '.join(unknown)}. Use --list to see available scenarios."
        )

    results = [
        evaluate_scenario(key, args.threshold, include_gnn=not args.no_gnn) for key in keys
    ]
    report = render_report(results, args.threshold)
    print(report)

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(report + "\n")
        print(f"\nWrote report to {args.output}", file=sys.stderr)


if __name__ == "__main__":
    main()
